# Python port of TypeScript 5.8 scripts/processDiagnosticMessages.mjs (info map only).
import json, re, sys
src = sys.argv[1]
table = json.load(open(src, encoding="utf-8"))
def prop(name):
    r = "".join("_Asterisk" if c == "*" else "_Slash" if c == "/" else "_Colon" if c == ":" else (c if re.match(r"\w", c, re.ASCII) else "_") for c in name)
    r = re.sub(r"_+", "_", r)
    r = re.sub(r"^_(\D)", r"\1", r)
    return re.sub(r"_$", "", r)
out = ["// <auto-generated />", f"// generated from '{src}'", "", 'import { DiagnosticCategory, DiagnosticMessage } from "./types.js";', "",
       "function diag(code: number, category: DiagnosticCategory, key: string, message: string, reportsUnnecessary?: {}, elidedInCompatabilityPyramid?: boolean, reportsDeprecated?: {}): DiagnosticMessage {",
       "    return { code, category, key, message, reportsUnnecessary, elidedInCompatabilityPyramid, reportsDeprecated };", "}", "",
       "/* eslint-disable @typescript-eslint/no-unnecessary-type-assertion*/", "/** @internal */", "export const Diagnostics = {"]
js = lambda v: "true" if v is True else "false" if v is False else json.dumps(v)
for name, d in table.items():
    p = prop(name); ru = d.get("reportsUnnecessary"); el = d.get("elidedInCompatabilityPyramid"); rd = d.get("reportsDeprecated")
    a1 = f", /*reportsUnnecessary*/ {js(ru)}" if ru else ""
    a2 = (("" if ru else ", /*reportsUnnecessary*/ undefined") + f", /*elidedInCompatabilityPyramid*/ {js(el)}") if el else ""
    a3 = (("" if a2 else ", /*reportsUnnecessary*/ undefined, /*elidedInCompatabilityPyramid*/ undefined") + f", /*reportsDeprecated*/ {js(rd)}") if rd else ""
    out.append(f'    {p}: diag({d["code"]}, DiagnosticCategory.{d["category"]}, "{p[:100]}_{d["code"]}", {json.dumps(name, ensure_ascii=False)}{a1}{a2}{a3}) as DiagnosticMessage,')
out.append("};")
open(src.rsplit("/", 1)[0] + "/diagnosticInformationMap.generated.ts", "w", encoding="utf-8").write("\r\n".join(out))
